// Split the two big master lists into evenly sized decks (~90 words) so every
// official deck is a comfortable study session rather than a 500-word wall.
const splitDeck = (baseId, baseName, words, size) => {
  const parts = [];
  for (let i = 0; i < words.length; i += size) parts.push(words.slice(i, i + size));
  return parts.map((slice, i) => ({
    id: `${baseId}-${i + 1}`,
    name: parts.length > 1 ? `${baseName} ${i + 1}` : baseName,
    visibility: "public",
    creator: "Jumsup Official",
    official: true,
    words: slice,
  }));
};

