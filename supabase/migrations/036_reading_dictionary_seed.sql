-- Reading passages' tap-to-translate feature (WordText.tsx -> /api/translate)
-- has three lookup tiers: the user's own flashcard decks, an offline
-- `dictionary_entries` table, then Google Translate if configured. Neither
-- `dictionary_entries` nor `dictionary_suggestions` (referenced by
-- functions/api/translate.js, functions/api/dictionary/suggest.js and
-- functions/api/admin/dictionary.js) had ever been created by a migration --
-- translate.js's own error handling even special-cases a missing
-- dictionary_entries table -- so translation only ever worked for a word
-- already sitting in one of the user's own decks, and returned nothing for
-- everything else. Without a configured GOOGLE_TRANSLATE_API_KEY there was no
-- fallback at all, which is why tapping most words in a reading passage
-- produced "ยังไม่พบคำแปล" (translation not found).
--
-- This creates both tables (schema matches the columns those three functions
-- already read/write) and seeds an approved Thai translation for every
-- distinct word that appears in the five official Reading sets, so tapping
-- any word in that content reliably shows a real translation and can be
-- added straight to a Flashcard deck, regardless of whether an online
-- translation provider is ever configured.

create table if not exists public.dictionary_entries (
  id bigint generated always as identity primary key,
  source_word text not null,
  normalized_word text not null,
  target_language text not null,
  meaning text not null,
  part_of_speech text,
  source text not null default 'jumsup-seed',
  status text not null default 'approved' check (status in ('approved','rejected')),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (normalized_word, target_language, meaning)
);
create index if not exists dictionary_entries_lookup_idx
  on public.dictionary_entries (normalized_word, target_language, status);

create table if not exists public.dictionary_suggestions (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  source_word text not null,
  normalized_word text not null,
  target_language text not null,
  suggested_meaning text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  unique (user_id, normalized_word, target_language, suggested_meaning)
);
create index if not exists dictionary_suggestions_pending_idx
  on public.dictionary_suggestions (status, created_at);

alter table public.dictionary_entries enable row level security;
alter table public.dictionary_suggestions enable row level security;

-- Both tables are only ever written through Cloudflare Functions using the
-- service-role key (which bypasses RLS); these policies just cover any
-- direct client read with the anon/authenticated key.
drop policy if exists dictionary_entries_read on public.dictionary_entries;
create policy dictionary_entries_read on public.dictionary_entries
  for select using (status = 'approved');
drop policy if exists dictionary_suggestions_self_read on public.dictionary_suggestions;
create policy dictionary_suggestions_self_read on public.dictionary_suggestions
  for select using (user_id = auth.uid());

